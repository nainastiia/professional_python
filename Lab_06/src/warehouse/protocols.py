from typing import Protocol, Iterator
from warehouse.models import WarehouseItem

class WarehouseRepository(Protocol):
    def get_by_code(self, code: str) -> WarehouseItem | None: ...
    def save(self, item: WarehouseItem) -> None: ...

class SupplierService(Protocol):
    def reorder(self, product_code: str, quantity: int) -> str: ...

class AsyncReorderProvider(Protocol):
    async def async_reorder(self, product_code: str, quantity: int) -> dict: ...